import { describe, expect, it } from "vitest";
import {
  formatCellId,
  getOperatorInfo,
  validateCellSurvey,
  type CurrentCellInfo,
} from "@solvex-dergana/shared";

describe("CellSurveyFrame Logic and Presets (FR-S4-08, FR-S4-09)", () => {
  const PRESET_TOWERS: CurrentCellInfo[] = [
    { mcc: 603, mnc: 1, lac: 100, cid: 5541, signalDbm: -68 }, // Mobilis
    { mcc: 603, mnc: 2, lac: 7, cid: 1204, signalDbm: -76 },   // Djezzy
    { mcc: 603, mnc: 3, lac: 44, cid: 8812, signalDbm: -82 },  // Ooredoo
  ];

  it("provides valid presets for all 3 major Algerian mobile operators", () => {
    const mobilis = getOperatorInfo(PRESET_TOWERS[0]!.mcc, PRESET_TOWERS[0]!.mnc);
    expect(mobilis.name).toBe("Mobilis");
    expect(mobilis.brandColor).toBe("#10b981");

    const djezzy = getOperatorInfo(PRESET_TOWERS[1]!.mcc, PRESET_TOWERS[1]!.mnc);
    expect(djezzy.name).toBe("Djezzy");
    expect(djezzy.brandColor).toBe("#ef4444");

    const ooredoo = getOperatorInfo(PRESET_TOWERS[2]!.mcc, PRESET_TOWERS[2]!.mnc);
    expect(ooredoo.name).toBe("Ooredoo");
    expect(ooredoo.brandColor).toBe("#f59e0b");
  });

  it("formats preset cell IDs cleanly for display in the survey frame", () => {
    expect(formatCellId(PRESET_TOWERS[0]!)).toBe("603-1-100-5541");
    expect(formatCellId(PRESET_TOWERS[1]!)).toBe("603-2-7-1204");
    expect(formatCellId(PRESET_TOWERS[2]!)).toBe("603-3-44-8812");
  });

  it("validates payload generated by the cell survey frame before tRPC mutation", () => {
    const payload = validateCellSurvey({
      ...PRESET_TOWERS[0]!,
      lat: 36.7538,
      lng: 3.0588,
      rangeM: 800,
    });

    expect(payload.source).toBe("survey");
    expect(payload.mcc).toBe(603);
    expect(payload.mnc).toBe(1);
    expect(payload.lat).toBe(36.7538);
    expect(payload.lng).toBe(3.0588);
    expect(payload.rangeM).toBe(800);
  });
});
