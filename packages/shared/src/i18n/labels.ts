export type Locale = "fr" | "ar";
const french = { shell: shell.fr, auth: auth.fr, navigation: navigation.fr, crash: crash.fr, victim: victim.fr, shock: shock.fr, live: live.fr, needs: needs.fr, hospital: hospital.fr, witness: witness.fr, console: { title: "Console de démonstration" } };
type Catalogue = { [S in keyof typeof french]: { [K in keyof typeof french[S]]: string } };
const arabic: { [S in keyof Catalogue]?: Partial<Catalogue[S]> } = { shell: shell.ar, auth: auth.ar, navigation: navigation.ar, crash: crash.ar, victim: victim.ar, shock: shock.ar, live: live.ar, needs: needs.ar, hospital: hospital.ar, witness: witness.ar };
export function getLabels<S extends keyof typeof french>(locale: Locale, section: S): { [K in keyof typeof french[S]]: string } {
  return { ...french[section], ...(locale === "ar" ? arabic[section] : {}) } as Catalogue[S];
}

/** Stable, sorted review report. Required Arabic scopes must never appear here. */
export function untranslatedKeys(): string[] {
  return (Object.keys(french) as (keyof Catalogue)[]).flatMap((section) => {
    const translated: Record<string, string> = arabic[section] ?? {};
    return Object.keys(french[section]).filter((key) => !translated[key]?.trim()).map((key) => `${section}.${key}`);
  }).sort();
}
